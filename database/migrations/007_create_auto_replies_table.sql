-- Create auto_replies table migration
CREATE TABLE IF NOT EXISTS `auto_replies` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `device_id` INT UNSIGNED NOT NULL,
  `user_id` INT UNSIGNED NOT NULL,
  `name` VARCHAR(255) NOT NULL,
  `match_type` ENUM('exact', 'contains', 'starts_with', 'ends_with', 'regex') NOT NULL,
  `keywords` TEXT NOT NULL,
  `reply_type` ENUM('text', 'image', 'video', 'document', 'audio') NOT NULL,
  `reply_text` TEXT NULL,
  `reply_media_url` VARCHAR(500) NULL,
  `reply_media_type` ENUM('image', 'video', 'document', 'audio') NULL,
  `is_active` BOOLEAN DEFAULT TRUE,
  `priority` INT DEFAULT 1,
  `cooldown_minutes` INT DEFAULT 0,
  `max_daily_replies` INT DEFAULT 0,
  `is_group_enabled` BOOLEAN DEFAULT FALSE,
  `time_start` TIME NULL,
  `time_end` TIME NULL,
  `delay_seconds` INT DEFAULT 0,
  `conditions` JSON NULL,
  `metadata` JSON NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  FOREIGN KEY (`device_id`) REFERENCES `devices`(`id`) ON DELETE CASCADE,
  FOREIGN KEY (`user_id`) REFERENCES `users`(`id`) ON DELETE CASCADE,
  INDEX `idx_auto_replies_device_id` (`device_id`),
  INDEX `idx_auto_replies_user_id` (`user_id`),
  INDEX `idx_auto_replies_match_type` (`match_type`),
  INDEX `idx_auto_replies_reply_type` (`reply_type`),
  INDEX `idx_auto_replies_is_active` (`is_active`),
  INDEX `idx_auto_replies_priority` (`priority`),
  INDEX `idx_auto_replies_device_active` (`device_id`, `is_active`),
  INDEX `idx_auto_replies_user_device` (`user_id`, `device_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;